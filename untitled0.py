# Split the 'Location' column by the first comma
split_location = fatality_locations['Location'].str.split(',', n=1, expand=True)

# Assign 'Region' from the first part of the split
fatality_locations['Region'] = split_location[0].str.strip()

# Assign 'Country' from the second part if it exists, otherwise assign NaN
# Use .get(1) to safely access the second element, which will return None if not present
# Then use .str.strip() and fillna(pd.NA) to handle potential None/NaN values consistently
fatality_locations['Country'] = split_location.get(1).str.strip().fillna(pd.NA)

