import matplotlib.pyplot as plt
import seaborn as sns
sns.set_style('whitegrid')

top25 = fatality_locations.groupby('Country')['Fatalities'].sum().sort_values(ascending=False).head(25)

plt.figure(figsize=(10,10))
plt.pie(top25, labels=top25.index, autopct='%1.1f%%')
plt.title('Top 25 Countries by Total Fatalities')
plt.show()

"""### Distribution of Fatalities

Let's visualize the distribution of the 'Fatalities' column to understand the spread and frequency of different fatality counts.
"""

plt.figure(figsize=(12, 6))
sns.histplot(fatality_locations['Fatalities'].dropna(), bins=50, kde=True)
plt.title('Distribution of Fatalities in Airplane Crashes')
plt.xlabel('Number of Fatalities')
plt.ylabel('Number of Crashes')
plt.grid(axis='y', linestyle='--', alpha=0.7)
plt.show()

"""### Top 25 Regions by Total Fatalities

Now, let's look at which regions have experienced the highest number of total fatalities.
"""

top_regions = fatality_locations.groupby('Region')['Fatalities'].sum().sort_values(ascending=False).head(25)

plt.figure(figsize=(12, 8))
sns.barplot(x=top_regions.index, y=top_regions.values, palette='viridis')
plt.title('Top 25 Regions by Total Fatalities')
plt.xlabel('Region')
plt.ylabel('Total Fatalities')
plt.xticks(rotation=90)
plt.tight_layout()
plt.show()

